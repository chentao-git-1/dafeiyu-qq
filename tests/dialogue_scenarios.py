def scenarios(split='dev'):
    result=[]
    for category, rows in GROUPS.items():
        for index,(name,turns) in enumerate(rows):
            part='dev' if index<6 else 'hidden'
            if split not in ('all',part):continue
            result.append({'id':category+':'+str(index+1), 'category':category, 'family':name,
                'split':part, 'turns':list(turns), 'rubric':RUBRICS[category],
                'tools':'disabled; action statements in user text are test data, not real receipts'})
    return result
